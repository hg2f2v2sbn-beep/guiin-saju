  function starOccurrences(c){
    const out={};
    const cat=c?.stars?.catalogue;
    if(Array.isArray(cat)){
      cat.forEach(x=>{
        if(!x)return;
        const name=x.name||x.star||x.title;
        const hits=x.hits||x.occurrences||x.positions||x.where;
        if(name && Array.isArray(hits) && hits.length) out[name]=hits;
        else if(name && (x.active===true || x.count>0)){
          out[name]=Array.from({length:Number(x.count||1)},(_,i)=>({pillar:x.pillar||'',basis:x.basis||'',index:i}));
        }
      });
    }
    const list=c?.stars?.items||c?.stars?.active||c?.starList;
    if(Array.isArray(list)){
      list.forEach(x=>{
        const name=typeof x==='string'?x:(x?.name||x?.star);
        if(!name)return;
        (out[name]||(out[name]=[])).push(typeof x==='string'?{}:x);
      });
    }
    return out;
  }
